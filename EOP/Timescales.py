def ut1_to_tt(ut1_jd1: float, ut1_jd2: float, delta_t: Optional[float] = None) -> Tuple[float, float]:
    """UT1 to TT via ΔT = TT − UT1."""
    ut1_jd = combine_jd(ut1_jd1, ut1_jd2)
    if delta_t is None:
        delta_t = delta_t_from_jd(ut1_jd)
    tt_jd = ut1_jd + delta_t / 86400.0
    return split_jd(tt_jd)

def tt_to_ut1(tt_jd1: float, tt_jd2: float, delta_t: Optional[float] = None) -> Tuple[float, float]:
    """TT to UT1 via ΔT = TT − UT1."""
    tt_jd = combine_jd(tt_jd1, tt_jd2)
    if delta_t is None:
        delta_t = delta_t_from_jd(tt_jd)
    ut1_jd = tt_jd - delta_t / 86400.0
    return split_jd(ut1_jd)

# ---------------------------------------------------------------------------
# TT to TDB (via TCG → TCB → TDB)
# ---------------------------------------------------------------------------
def tt_to_tdb(tt_jd1: float, tt_jd2: float) -> Tuple[float, float]:
    """
    Convert TT to TDB using the full relativistic chain:
    TT → TCG → TCB → TDB.

    This is accurate to a few nanoseconds (IERS Conventions 2010).

    Parameters
    ----------
    tt_jd1, tt_jd2 : float
        Two-part Julian Date in TT.

    Returns
    -------
    tdb_jd1, tdb_jd2 : float
        Two-part Julian Date in TDB.
    """
    tt_jd = combine_jd(tt_jd1, tt_jd2)
    # 1. TT → TCG
    tcg_jd = tt_jd + LG * (tt_jd - T0_JD)
    # 2. TCG → TCB (using HF2002 model)
    delta_tcb_tcg = hf2002_iers(tt_jd)
    tcb_jd = tcg_jd + delta_tcb_tcg / 86400.0
    # 3. TCB → TDB
    tdb_jd = tcb_jd - LB * (tcb_jd - T0_JD) + TDB0 / 86400.0
    return split_jd(tdb_jd)


def tdb_to_tt(tdb_jd1: float, tdb_jd2: float) -> Tuple[float, float]:
    """
    Convert TDB to TT (inverse of tt_to_tdb). Iterative solution because
    TT is needed to compute TCB−TCG.
    """
    tdb_jd = combine_jd(tdb_jd1, tdb_jd2)
    # Initial estimate: assume TT ≈ TDB
    tt_jd = tdb_jd
    for _ in range(3):
        tcg_jd = tt_jd + LG * (tt_jd - T0_JD)
        delta_tcb_tcg = hf2002_iers(tt_jd)
        tcb_jd = tcg_jd + delta_tcb_tcg / 86400.0
        tdb_est = tcb_jd - LB * (tcb_jd - T0_JD) + TDB0 / 86400.0
        tt_jd = tt_jd - (tdb_est - tdb_jd)   # simple Newton step
    return split_jd(tt_jd)


