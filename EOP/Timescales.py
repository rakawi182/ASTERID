def _delta_t_s15(year):
    """Evaluasi segmen polinomial Tabel S15."""
    K     = _TABLE_S15[:, 0]
    Knext = _TABLE_S15[:, 1]
    a0, a1, a2, a3 = _TABLE_S15[:, 2], _TABLE_S15[:, 3], _TABLE_S15[:, 4], _TABLE_S15[:, 5]
    if year < K[0]:
        i, t = 0, (year - K[0]) / (Knext[0] - K[0])
    elif year >= Knext[-1]:
        i, t = -1, (year - K[-1]) / (Knext[-1] - K[-1])
    else:
        for i in range(len(K)):
            if K[i] <= year < Knext[i]:
                break
        t = (year - K[i]) / (Knext[i] - K[i])
    return a0[i] + a1[i]*t + a2[i]*t*t + a3[i]*t*t*t

def delta_t_historical(year):
    """
    ΔT historis (detik) menggunakan PCHIP Hermite.
    - year < -720     : Parabola pasang surut
    - -720 ≤ year ≤ 1600 : PCHIP (JRC + SMH2016)
    - 1600 < year ≤ 1620 : Transisi linear
    - year > 1620     : Tabel S15
    """
    if year < -720.0:
        t = (year - 1820.0) / 100.0
        return 32.0 * t * t

    if year <= 1600.0:
        return float(_pchip_historical(year))

    if year <= 1620.0:
        dt_1600 = float(_pchip_historical(1600.0))
        dt_1620 = _delta_t_s15(1620.0)
        frac = (year - 1600.0) / 20.0
        return dt_1600 + frac * (dt_1620 - dt_1600)

    return _delta_t_s15(year)

def delta_t_from_jd(jd: float, dut1: Optional[float] = None) -> float:
    """
    High-Precision Ensemble ΔT = TT - UT1 (seconds).

    Strategi hibrida:
    1. Jika MJD berada dalam rentang data EOP C04 (1962–sekarang):
         ΔT = 32.184 + TAI−UTC - (UT1−UTC)
       (UT1−UTC diambil dari EOPProvider jika dut1 tidak diberikan)
    2. Jika MJD di luar rentang C04 (epoch kuno atau masa depan):
         - Untuk tahun ≤ 1790: gunakan delta_t_historical(year)
         - Untuk tahun ≥ 1810: gunakan delta_t_from_mjd_safe(mjd)
         - Antara 1790–1810: transisi kosinus halus
    """
    mjd = jd - 2400000.5
    eop = _get_eop_provider()   # instance singleton dari EOPProvider

    # ------------------------------------------------------------------
    # 1. PRIORITAS UTAMA: Data C04 (1962–sekarang)
    # ------------------------------------------------------------------
    if eop._loaded and (eop.mjd[0] <= mjd <= eop.mjd[-1]):
        if dut1 is None:
            dut1 = eop.get_eop(mjd)['ut1_utc']
        tai_minus_utc = tai_utc(mjd)
        return 32.184 + tai_minus_utc - dut1

    # ------------------------------------------------------------------
    # 2. FALLBACK: Model historis (untuk epoch di luar data C04)
    # ------------------------------------------------------------------
    year = 2000.0 + (jd - 2451545.0) / 365.2425   # tahun desimal

    if year <= 1790.0:
        return delta_t_historical(year)
    elif year >= 1810.0:
        return delta_t_from_mjd_safe(mjd)
    else:
        # Transisi halus antara 1790–1810 (cosine blend)
        dt_hist = delta_t_historical(year)
        dt_mod  = delta_t_from_mjd_safe(mjd)
        w = 0.5 * (1.0 - math.cos(math.pi * (year - 1790.0) / 20.0))
        return dt_hist * (1.0 - w) + dt_mod * w

def delta_t_from_mjd_safe(mjd: float) -> float:
    """Wrapper untuk mengamankan pembacaan tabel MJD."""
    try:
        return delta_t_from_mjd(mjd)
    except RuntimeError:
        year = 2000.0 + (mjd - 51544.5) / 365.2425
        return delta_t_espenak_extended(year)

