# ---------------------------------------------------------------------------
# Auxiliary functions: Julian Date splitting/combining
# ---------------------------------------------------------------------------
def split_jd(jd: float) -> Tuple[float, float]:
    """
    Split a Julian Date into two parts (high precision).

    Parameters
    ----------
    jd : float
        Julian Date.

    Returns
    -------
    jd1, jd2 : tuple of float
        Two parts such that jd1 + jd2 = jd.
        Typically jd1 is the integer part and jd2 the fractional part.
    """
    jd1 = math.floor(jd)
    jd2 = jd - jd1
    return jd1, jd2

def combine_jd(jd1: float, jd2: float) -> float:
    """Combine two parts into a single Julian Date."""
    return jd1 + jd2

