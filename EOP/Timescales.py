def hf2002_iers(tjd: float) -> float:
    """
    Compute TCB − TCG (seconds) using the IERS 2010 HF2002 model.

    Parameters
    ----------
    tjd : float
        Julian Date (TT or TDB). Accuracy is unaffected if TT is used.

    Returns
    -------
    float
        TCB − TCG in seconds, including the linear correction term
        C4TERMS × (tjd − T0_JD) × 86400 as per IERS Conventions.
    """
    N = 73000
    NE = 463
    NX = 36
    T_START = 2305450.5
    C4TERMS = 1.15e-16

    PI2 = 8.0 * math.atan(1.0)
    CN1DT = 3.0 * float(N - 1)
    CNDTI = 4.0 / CN1DT

    T = (tjd - T_START) - 0.5 * CN1DT
    PI2T = PI2 * T
    XI = CNDTI * T

    # Secular part (first term)
    a0, b0, c0 = _HFDATA[0]
    s0 = a0 + XI * (b0 + c0 * XI)

    # Fourier part (463 terms)
    s1 = 0.0
    for i in range(1, NE + 1):
        a, b, f = _HFDATA[i]
        arg = PI2T * f
        s1 += a * math.sin(arg) + b * math.cos(arg)

    # Mixed secular part (36 terms)
    s2 = 0.0
    for i in range(NE + 1, NE + NX + 1):
        a, b, f = _HFDATA[i]
        arg = PI2T * f
        s2 += XI * (a * math.sin(arg) + b * math.cos(arg))

    hf = (s2 + s1) + s0
    # Linear correction from IERS Conventions
    hf_iers = hf / (1.0 - LB) + C4TERMS * (tjd - T0_JD) * 86400.0
    return hf_iers

