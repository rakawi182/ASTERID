def delta_t_from_mjd(mjd: float) -> float:
    """Catmull‑Rom spline pada tabel ΔT modern → C¹ smooth, tanpa zig‑zag."""
    if not _MJD:
        raise RuntimeError("Delta T table is empty.")
    if mjd <= _MJD[0]:
        return _DT[0]
    if mjd >= _MJD[-1]:
        return _DT[-1]

    idx = bisect.bisect_left(_MJD, mjd)
    if idx == 0:
        return _DT[0]

    i1, i2 = idx - 1, idx
    i0 = max(0, i1 - 1)
    i3 = min(len(_MJD) - 1, i2 + 1)

    t = (mjd - _MJD[i1]) / (_MJD[i2] - _MJD[i1])
    v0, v1, v2, v3 = _DT[i0], _DT[i1], _DT[i2], _DT[i3]

    a = 2.0 * v1
    b = v2 - v0
    c = 2.0 * v0 - 5.0 * v1 + 4.0 * v2 - v3
    d = -v0 + 3.0 * v1 - 3.0 * v2 + v3

    return 0.5 * (a + b * t + c * t*t + d * t*t*t)

