class TimeScaleConverter:
    """
    A high-level converter between astronomical time scales.

    This class provides a unified interface for converting times between
    UTC, UT1, TAI, TT, TCG, TCB, and TDB, using IERS Conventions models.
    """
    def __init__(self, eop_file: str = "EOP_20u24_C04_one_file_1962-now.txt"):
        # Gunakan EOPProvider dari EOPDelta
        self.eop = EOPProvider(eop_file)

    def utc_to_tt(self, utc_jd: float) -> float:
        """Convert UTC (JD) to TT (JD)."""
        jd1, jd2 = split_jd(utc_jd)
        tai1, tai2 = utc_to_tai(jd1, jd2)
        tt1, tt2 = tai_to_tt(tai1, tai2)
        return combine_jd(tt1, tt2)

    def tt_to_utc(self, tt_jd: float) -> float:
        """Convert TT (JD) to UTC (JD)."""
        jd1, jd2 = split_jd(tt_jd)
        tai1, tai2 = tt_to_tai(jd1, jd2)
        utc1, utc2 = tai_to_utc(tai1, tai2)
        return combine_jd(utc1, utc2)

    def tt_to_tdb(self, tt_jd: float) -> float:
        """Convert TT (JD) to TDB (JD)."""
        jd1, jd2 = split_jd(tt_jd)
        tdb1, tdb2 = tt_to_tdb(jd1, jd2)
        return combine_jd(tdb1, tdb2)

    def tdb_to_tt(self, tdb_jd: float) -> float:
        """Convert TDB (JD) to TT (JD)."""
        jd1, jd2 = split_jd(tdb_jd)
        tt1, tt2 = tdb_to_tt(jd1, jd2)
        return combine_jd(tt1, tt2)

    def utc_to_tdb(self, utc_jd: float) -> float:
        """Convert UTC directly to TDB (via TAI→TT→TCG→TCB→TDB)."""
        tt_jd = self.utc_to_tt(utc_jd)
        return self.tt_to_tdb(tt_jd)

    def tdb_to_utc(self, tdb_jd: float) -> float:
        """Convert TDB to UTC (reverse chain)."""
        tt_jd = self.tdb_to_tt(tdb_jd)
        return self.tt_to_utc(tt_jd)

    def ut1_utc(self, mjd: float) -> float:
        """Get UT1−UTC (seconds) from EOP file for given MJD."""
        return self.eop.get_eop(mjd)['ut1_utc']

    def delta_t(self, jd: float) -> float:
        """Compute ΔT = TT−UT1 for given JD, using EOP if available."""
        mjd = jd - MJD_ZERO
        if mjd >= self.eop.mjd_list[0] and mjd <= self.eop.mjd_list[-1]:
            dut1 = self.eop.get_eop(mjd)['ut1_utc']
            return delta_t_from_jd(jd, dut1=dut1)
        else:
            return delta_t_from_jd(jd, dut1=None)

