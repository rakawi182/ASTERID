def tai_utc(mjd: float) -> float:
    """
    Return TAI−UTC offset (seconds) for a given Modified Julian Date.

    For MJD >= 41317 (1972-01-01) uses the leap second table.
    For MJD between 37300 and 41317 (1961–1972) uses linear drift formulas
    from IERS Conventions.
    For MJD < 37300 (pre-1961) returns the constant 1.42281805 s (value at
    1961-01-01).
    """
    # Pre-1961: constant TAI-UTC = 1.42281805 s
    if mjd < 37300.0:
        return 1.42281805
    # Modern era (1972 onwards)
    if mjd >= 41317.0:
        offset = _LEAP_SECONDS[-1][1]
        for m, off in _LEAP_SECONDS:
            if m <= mjd:
                offset = off
            else:
                break
        return offset
    # Historical linear drifts 1961–1972 (IERS Conventions)
    # Data: (start_mjd, end_mjd, base_offset_s, rate_s_per_day)
    historical = [
        (37300.0, 37512.0, 1.42281805, 0.001296),
        (37512.0, 37665.0, 1.37281805, 0.001296),
        (37665.0, 38334.0, 1.84585805, 0.00112325),
        (38334.0, 38761.0, 1.94585805, 0.00112325),
        (38761.0, 38852.0, 3.24013005, 0.001296),
        (38852.0, 39005.0, 3.34013005, 0.001296),
        (39005.0, 39127.0, 3.44013005, 0.001296),
        (39127.0, 39186.0, 3.54013005, 0.001296),
        (39186.0, 39308.0, 3.64013005, 0.001296),
        (39308.0, 39370.0, 3.74013005, 0.001296),
        (39370.0, 39487.0, 3.84013005, 0.001296),
        (39487.0, 39883.0, 4.31317005, 0.002592),
        (39883.0, 41317.0, 4.21317005, 0.002592),
    ]
    for start, end, base, rate in historical:
        if start <= mjd < end:
            return base + (mjd - start) * rate
    # Fallback
    return _LEAP_SECONDS[0][1]

