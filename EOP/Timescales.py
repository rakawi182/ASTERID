def cosine_blend(val1: float, val2: float, t: float, t0: float, t1: float) -> float:
    """
    Transisi kosinus halus dari val1 ke val2 di antara t0 dan t1.
    Memastikan tidak ada lonjakan nilai (step-discontinuity) pada batas data.
    """
    if t <= t0: return val1
    if t >= t1: return val2
    weight = 0.5 * (1.0 - math.cos(math.pi * (t - t0) / (t1 - t0)))
    return val1 * (1.0 - weight) + val2 * weight

