# Basic time scale conversions (adjacent pairs)
# ---------------------------------------------------------------------------
def utc_to_tai(utc_jd1: float, utc_jd2: float) -> Tuple[float, float]:
    """UTC (two-part JD) to TAI (two-part JD)."""
    utc_jd = combine_jd(utc_jd1, utc_jd2)
    mjd = utc_jd - MJD_ZERO
    offset = tai_utc(mjd)
    tai_jd = utc_jd + offset / 86400.0
    return split_jd(tai_jd)

def tai_to_utc(tai_jd1: float, tai_jd2: float) -> Tuple[float, float]:
    """TAI (two-part JD) to UTC (two-part JD)."""
    tai_jd = combine_jd(tai_jd1, tai_jd2)
    # Approximate UTC by subtracting the latest offset, then refine
    utc_jd = tai_jd - _LEAP_SECONDS[-1][1] / 86400.0
    # Iterate once to correct (standard method)
    mjd_utc = utc_jd - MJD_ZERO
    offset = tai_utc(mjd_utc)
    utc_jd = tai_jd - offset / 86400.0
    return split_jd(utc_jd)

def utc_to_ut1(utc_jd1: float, utc_jd2: float, dut1: float) -> Tuple[float, float]:
    """UTC to UT1 using ΔUT1 = UT1−UTC (seconds)."""
    utc_jd = combine_jd(utc_jd1, utc_jd2)
    ut1_jd = utc_jd + dut1 / 86400.0
    return split_jd(ut1_jd)

def ut1_to_utc(ut1_jd1: float, ut1_jd2: float, dut1: float) -> Tuple[float, float]:
    """UT1 to UTC using ΔUT1 = UT1−UTC (seconds)."""
    ut1_jd = combine_jd(ut1_jd1, ut1_jd2)
    utc_jd = ut1_jd - dut1 / 86400.0
    return split_jd(utc_jd)

def tai_to_tt(tai_jd1: float, tai_jd2: float) -> Tuple[float, float]:
    """TAI to TT (add fixed offset 32.184 s)."""
    tai_jd = combine_jd(tai_jd1, tai_jd2)
    tt_jd = tai_jd + TAI_TT_OFFSET / 86400.0
    return split_jd(tt_jd)

def tt_to_tai(tt_jd1: float, tt_jd2: float) -> Tuple[float, float]:
    """TT to TAI (subtract fixed offset)."""
    tt_jd = combine_jd(tt_jd1, tt_jd2)
    tai_jd = tt_jd - TAI_TT_OFFSET / 86400.0
    return split_jd(tai_jd)

def tt_to_tcg(tt_jd1: float, tt_jd2: float) -> Tuple[float, float]:
    """TT to TCG (linear transformation)."""
    tt_jd = combine_jd(tt_jd1, tt_jd2)
    tcg_jd = tt_jd + LG * (tt_jd - T0_JD)
    return split_jd(tcg_jd)

def tcg_to_tt(tcg_jd1: float, tcg_jd2: float) -> Tuple[float, float]:
    """TCG to TT (inverse linear transformation)."""
    tcg_jd = combine_jd(tcg_jd1, tcg_jd2)
    # Solve tt_jd = tcg_jd - LG*(tt_jd - T0_JD)
    # => tt_jd = (tcg_jd + LG*T0_JD) / (1 + LG)
    tt_jd = (tcg_jd + LG * T0_JD) / (1.0 + LG)
    return split_jd(tt_jd)

def tcb_to_tdb(tcb_jd1: float, tcb_jd2: float) -> Tuple[float, float]:
    """TCB to TDB (linear transformation, IAU 2006)."""
    tcb_jd = combine_jd(tcb_jd1, tcb_jd2)
    tdb_jd = tcb_jd - LB * (tcb_jd - T0_JD) + TDB0 / 86400.0
    return split_jd(tdb_jd)

def tdb_to_tcb(tdb_jd1: float, tdb_jd2: float) -> Tuple[float, float]:
    """
    TDB to TCB (inverse linear transformation, IAU 2006).
    
    References:
        IAU 2006 Resolution B3
    """
    tdb_jd = combine_jd(tdb_jd1, tdb_jd2)
    # TDB = TCB - LB * (TCB - T0) + TDB0/86400
    # => TCB = (TDB - LB*T0 - TDB0/86400) / (1 - LB)
    tcb_jd = (tdb_jd - LB * T0_JD - TDB0 / 86400.0) / (1.0 - LB)
    return split_jd(tcb_jd)

# ---------------------------------------------------------------------------
# Earth Rotation Angle (ERA)
# ---------------------------------------------------------------------------
def era(ut1_jd: float) -> float:
    """
    Earth Rotation Angle (radians) as a function of UT1.

    Parameters
    ----------
    ut1_jd : float
        Julian Date in UT1.

    Returns
    -------
    float
        Earth Rotation Angle in radians (range [0, 2π)).
    """
    t_u = ut1_jd - J2000_JD
    era_rev = ERA0 + ERA_RATE * t_u   # revolutions
    era_rad = 2.0 * math.pi * (era_rev % 1.0)
    return era_rad

