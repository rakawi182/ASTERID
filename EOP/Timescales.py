def cal_to_jd(year: int, month: int, day: int,
              hour: int = 0, minute: int = 0, second: float = 0.0,
              scale: str = 'utc') -> Tuple[float, float]:
    """
    Convert Gregorian calendar date to two-part Julian Date.

    Parameters
    ----------
    year, month, day : int
        Gregorian calendar date (proleptic).
    hour, minute : int, optional
        Hours (0-23) and minutes (0-59).
    second : float, optional
        Seconds (including fraction).
    scale : str, optional
        Time scale of the input ('utc', 'tai', 'tt', etc.). Only affects
        interpretation for UTC (leap seconds are handled by the encoding
        function; here we treat the input as a simple fraction of day).

    Returns
    -------
    jd1, jd2 : tuple of float
        Two-part Julian Date (sum = JD).
    """
    # Gregorian to JD (algorithm from SOFA iauCal2jd)
    if month <= 2:
        y = year - 1
        m = month + 12
    else:
        y = year
        m = month

    # Proleptic Gregorian (always use Gregorian rules)
    a = y // 100
    b = 2 - a + (a // 4)

    jd = (math.floor(365.25 * (y + 4716)) +
          math.floor(30.6001 * (m + 1)) +
          day + b - 1524.5)

    # Fraction of day
    day_frac = (hour + (minute + second / 60.0) / 60.0) / 24.0
    jd += day_frac
    return split_jd(jd)

def jd_to_cal(jd1: float, jd2: float, scale: str = 'utc') -> Dict:
    """
    Convert two-part Julian Date to Gregorian calendar date and time.

    Parameters
    ----------
    jd1, jd2 : float
        Two-part Julian Date (sum = JD).
    scale : str, optional
        Time scale (for information only, not used in conversion).

    Returns
    -------
    dict
        Contains keys: year, month, day, hour, minute, second, scale.
    """
    jd = combine_jd(jd1, jd2) + 0.5   # JD at midnight
    i = math.floor(jd)
    f = jd - i

    if i > 2299160:   # Gregorian calendar
        a = math.floor((i - 1867216.25) / 36524.25)
        b = i + 1 + a - math.floor(a / 4)
    else:
        b = i

    c = b + 1524
    d = math.floor((c - 122.1) / 365.25)
    e = math.floor(365.25 * d)
    g = math.floor((c - e) / 30.6001)

    day = c - e + f - math.floor(30.6001 * g)
    if g < 13.5:
        month = g - 1
    else:
        month = g - 13
    if month > 2.5:
        year = d - 4716
    else:
        year = d - 4715

    day_int = int(day)
    frac = day - day_int
    hour = int(frac * 24)
    frac = frac * 24 - hour
    minute = int(frac * 60)
    second = (frac * 60 - minute) * 60

    return {
        'year': year,
        'month': month,
        'day': day_int,
        'hour': hour,
        'minute': minute,
        'second': second,
        'scale': scale
    }

