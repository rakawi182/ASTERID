    if jd <= _ANCHOR_JDS[0]:
        a = _ECLIPSE_ANCHORS_BY_JD[_ANCHOR_JDS[0]]
        return a['delta_t'], a['reliability']
    if jd >= _ANCHOR_JDS[-1]:
        a = _ECLIPSE_ANCHORS_BY_JD[_ANCHOR_JDS[-1]]
        return a['delta_t'], a['reliability']

    idx = bisect.bisect_left(_ANCHOR_JDS, jd)
    jd1 = _ANCHOR_JDS[idx-1]
    jd2 = _ANCHOR_JDS[idx]
    a1 = _ECLIPSE_ANCHORS_BY_JD[jd1]
    a2 = _ECLIPSE_ANCHORS_BY_JD[jd2]

    frac = (jd - jd1) / (jd2 - jd1)
    dt = a1['delta_t'] * (1 - frac) + a2['delta_t'] * frac
    rel = a1['reliability'] * (1 - frac) + a2['reliability'] * frac
    return dt, rel

