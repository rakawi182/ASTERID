# ======================================================================
# MAIN
# ======================================================================
def main():
    print(f"{BOLD}Memuat seri VSOP2013 dan ELP/MPP02...{RESET}")
    vsop = VSOP2013('VSOP2013p3.dat')
    if not ELP_MPP02_full.SERIES['long'].main:
        ELP_MPP02_full.load_all_series()
    print(f"{BOLD}Selesai.{RESET}\n")

    all_jd = sorted(EARTH_HOR.keys())

    # Lebar diatur agar total presisi persis 70 karakter
    print(f"{BOLD}{'=' * 70}{RESET}")
    print(f"{BOLD}{'JD':>10} {'Tahun':>7} {'ErrEMB(km)':>11} {'ErrBumi(km)':>11} "
          f"{'Lon(\")':>9} {'Rad(km)':>10} {'t(cy)':>7}{RESET}")
    print(f"{BOLD}{'-' * 70}{RESET}")

    results = []

    for jd in all_jd:
        tdj = jd - J2000_JD
        t_cent = tdj / 36525.0
        year = 2000.0 + tdj / 365.25

        emb_el = vsop._read_elliptic_variables(3, tdj)
        emb_state = vsop._ellxyz(3, emb_el)
        pos_emb_vsop = np.array(emb_state[0:3]) * AU2KM

        moon = ELP_MPP02_full.elpmpp02(tdj, icor=1)
        pos_moon = np.array(moon[0:3])
        pos_earth_vsop = pos_emb_vsop - MU * pos_moon

        hemb = EMB_HOR[jd]
        hearth = EARTH_HOR[jd]

        err_emb = np.linalg.norm(pos_emb_vsop - hemb['pos'])
        err_earth = np.linalg.norm(pos_earth_vsop - hearth['pos'])

        x1, y1, _ = hemb['pos']
        x2, y2, _ = pos_emb_vsop
        cross = x1*y2 - y1*x2
        dot = x1*x2 + y1*y2
        lon_err_rad = math.atan2(cross, dot)
        lon_err_arcsec = lon_err_rad * RAD2ARCSEC

        r_emb_vsop = np.linalg.norm(pos_emb_vsop)
        r_emb_hor = np.linalg.norm(hemb['pos'])
        radial_err = r_emb_vsop - r_emb_hor

        results.append({
            'jd': jd,
            'year': year,
            't_cent': t_cent,
            'err_emb': err_emb,
            'err_earth': err_earth,
            'lon_err': lon_err_arcsec,
            'radial_err': radial_err
        })

        # Total formatting: 10+1+7+1+11+1+11+1+9+1+10+1+7 = 70 karakter
        print(f"{jd:10.1f} {year:7.0f} {err_emb:11.3f} {err_earth:11.3f} "
              f"{lon_err_arcsec:9.4f} {radial_err:10.3f} {t_cent:7.1f}")

    print(f"{BOLD}{'=' * 70}{RESET}")

    # ==================================================================
    # RINGKASAN DRIFT
    # ==================================================================
    print("\n" + f"{BOLD}{'=' * 50}{RESET}")
    print(f"{BOLD}{'RINGKASAN DRIFT (ERROR BUJUR)':^50}{RESET}")
    print(f"{BOLD}{'=' * 50}{RESET}")
    print(f"{BOLD}{'t (dari J2000)':>16} {'Tahun (M)':>12} {'Error Bujur (\")':>18}{RESET}")
    print(f"{BOLD}{'-' * 50}{RESET}")

    for r in results:
        t_val = r['t_cent']
        if t_val % 5.0 == 0.0:
            print(f"{t_val:16.1f} {r['year']:12.0f} {r['lon_err']:18.4f}")

    print(f"{BOLD}{'=' * 50}{RESET}")

if __name__ == "__main__":
    main()
